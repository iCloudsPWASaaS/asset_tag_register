import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";
import type { Asset } from "@/lib/types";
import { formatDate } from "@/lib/utils";

export function buildRegisterPdf(input: {
  companyName: string;
  assets: Asset[];
  generatedBy?: string;
}) {
  const doc = new jsPDF({ orientation: "landscape", unit: "pt", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  doc.setFillColor(15, 23, 42);
  doc.rect(0, 0, pageWidth, 64, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text("Asset Tag Register", 32, 30);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(199, 210, 254);
  doc.text(
    `${input.companyName || "Asset register"}  •  Generated ${formatDate(new Date().toISOString())}  •  ${input.assets.length} asset${input.assets.length === 1 ? "" : "s"}`,
    32,
    48,
  );
  if (input.generatedBy) {
    doc.text(input.generatedBy, pageWidth - 32, 48, { align: "right" });
  }

  autoTable(doc, {
    startY: 82,
    head: [
      [
        "Tag",
        "Premises",
        "Address",
        "Location",
        "Type",
        "Make",
        "Model",
        "Serial no.",
        "Status",
        "Installed",
        "Engineer",
        "Manual",
        "Notes",
        "Updated",
      ],
    ],
    body: input.assets.map((asset) => [
      asset.tag,
      asset.premisesName,
      asset.premisesAddress,
      asset.location,
      asset.type,
      asset.make,
      asset.model,
      asset.serialNumber,
      asset.status,
      asset.installedAt ? formatDate(asset.installedAt) : "",
      asset.engineer,
      asset.manual ? (asset.manual.status === "ai" ? "AI guidance" : "Search links") : "—",
      asset.notes,
      formatDate(asset.updatedAt),
    ]),
    styles: {
      font: "helvetica",
      fontSize: 7.5,
      cellPadding: 4,
      overflow: "linebreak",
      textColor: [30, 41, 59],
      lineColor: [226, 232, 240],
      lineWidth: 0.4,
    },
    headStyles: {
      fillColor: [79, 70, 229],
      textColor: [255, 255, 255],
      fontStyle: "bold",
      fontSize: 7.5,
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    columnStyles: {
      0: { cellWidth: 52, fontStyle: "bold" },
      1: { cellWidth: 92 },
      2: { cellWidth: 112 },
      3: { cellWidth: 64 },
      4: { cellWidth: 78 },
      5: { cellWidth: 58 },
      6: { cellWidth: 78 },
      7: { cellWidth: 66 },
      8: { cellWidth: 46 },
      9: { cellWidth: 52 },
      10: { cellWidth: 62 },
      11: { cellWidth: 52 },
      12: { cellWidth: 120 },
      13: { cellWidth: 52 },
    },
    margin: { left: 32, right: 32, bottom: 34 },
    didDrawPage: () => {
      doc.setFontSize(8);
      doc.setTextColor(100, 116, 139);
      doc.text(
        "Generated by AssetTag Register",
        32,
        pageHeight - 16,
      );
    },
  });

  const pageCount = doc.getNumberOfPages();
  for (let page = 1; page <= pageCount; page += 1) {
    doc.setPage(page);
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text(`Page ${page} of ${pageCount}`, pageWidth - 32, pageHeight - 16, {
      align: "right",
    });
  }

  return Buffer.from(doc.output("arraybuffer"));
}
